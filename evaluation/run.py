"""Run OpsPilot evaluations and write a Markdown + JSON report.

Usage (from the repo root; needs docker compose services and Ollama):
  uv run --project backend python evaluation/run.py                      # retrieval A-D on the test split
  uv run --project backend python evaluation/run.py --split tune         # tuning split
  uv run --project backend python evaluation/run.py --answers --limit 30 # grounded-answer checks (slow: LLM)

Every number in the report comes from this run; nothing is entered by hand.
"""

import argparse
import asyncio
import json
import platform
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / "backend"))

from app.core.config import get_settings  # noqa: E402
from app.db.session import dispose_engine, get_sessionmaker  # noqa: E402
from app.evaluations.runner import RETRIEVAL_CONFIGS, load_dataset, run_answers, run_retrieval  # noqa: E402
from app.rag.embeddings.provider import get_embedding_provider  # noqa: E402
from app.rag.generation.llm import get_llm  # noqa: E402

COLS = [("recall_at_5", "Recall@5"), ("recall_at_10", "Recall@10"), ("precision_at_5", "P@5"), ("mrr", "MRR"),
        ("ndcg_at_5", "nDCG@5"), ("ndcg_at_10", "nDCG@10"), ("latency_p50_ms", "p50 ms"), ("latency_p95_ms", "p95 ms")]


RETRIEVAL_NOTES = [
    "Relevance is binary at section level; unanswerable questions are excluded from retrieval metrics.",
    "Lexical retrieval is PostgreSQL full-text search (`ts_rank_cd`), not BM25.",
    "Latency is measured in-process on this machine and includes query embedding (and reranking for D).",
    "Synthetic corpus; small sample. These numbers do not predict production performance.",
]
ANSWER_NOTES = [
    "abstention_accuracy: answers answerable questions and abstains on unanswerable ones.",
    "citation_precision / citation_coverage: cited chunks that are in an expected section / answers with at least one such citation (answered, answerable questions only).",
    "expected_fact_match: every expected key phrase appears verbatim in the answer; it under-counts correct paraphrases.",
    "faithfulness: share of answer claims that an LLM judge (same local model family) finds supported by the evidence the claim cites; the judge can share the generator's blind spots, so treat it as an estimate checked against the human spot-check sheet.",
    "Latency includes retrieval and local LLM generation on one laptop.",
    "Synthetic corpus; small sample. These numbers do not predict production performance.",
]


def retrieval_note(config: dict) -> str:
    """Describe the retrieval an answers run actually used, from its stored config."""
    w, rr = config.get("lexical_weight"), config.get("reranker")
    how = f"weighted RRF (lexical weight {w}, depth {config.get('lexical_depth')})" if w else "equal-weight RRF (config C)"
    if rr:
        how += f", then the `{rr}` cross-encoder"
    return f"Retrieval: {how}. Answers come from the local LLM with citation and number validation."


async def write_results(db) -> Path:  # type: ignore[no-untyped-def]
    """Regenerate evaluation/RESULTS.md from the latest completed full test-split runs, per dataset version."""
    from sqlalchemy import select

    from app.evaluations.runner import available_versions
    from app.models import EvaluationRun

    async def latest(label: str, version: str) -> EvaluationRun | None:
        rows = await db.scalars(select(EvaluationRun).where(
            EvaluationRun.config_label == label, EvaluationRun.status == "completed",
            EvaluationRun.split == "test", EvaluationRun.dataset_version == version,
        ).order_by(EvaluationRun.finished_at.desc()).limit(10))
        # runs limited to a subset of questions are not comparable; skip them
        return next((r for r in rows if not (r.config or {}).get("limit")), None)

    lines = ["# OpsPilot evaluation results", "",
             "Generated by `evaluation/run.py` from the latest completed runs on each dataset's **held-out test split**.",
             "Do not edit by hand: `make eval`, `make eval-answers`, `make eval-extra` (tool selection + injection),",
             "or `make eval-results` to rebuild this file from stored runs.",
             "Method and limitations: [evaluation/README.md](README.md)."]
    for version in sorted(available_versions(), reverse=True):
        retrieval = {label: await latest(label, version) for label in RETRIEVAL_CONFIGS}
        done = {k: r for k, r in retrieval.items() if r is not None}
        answers = await latest("answers_hybrid_rrf", version)
        extra = {k: await latest(k, version) for k in ("tool_selection_planner", "injection_resistance")}
        if not done and answers is None and not any(extra.values()):
            continue
        lines += ["", f"## Dataset {version}", "", "### Retrieval", ""]
        if done:
            first = next(iter(done.values()))
            lines += [f"Hash `{first.dataset_hash[:16]}`; {(first.metrics or {}).get('answerable_questions')} answerable of "
                      f"{(first.metrics or {}).get('questions')} test questions; embedding model "
                      f"`{first.config.get('embedding_model')}`.", "",
                      "| Config | " + " | ".join(c for _, c in COLS) + " | Run (UTC) |", "|---" * (len(COLS) + 2) + "|"]
            for label, r in done.items():
                m = r.metrics or {}
                lines.append(f"| {label} | " + " | ".join(fmt(m.get(k, "—")) for k, _ in COLS)
                             + f" | {r.finished_at:%Y-%m-%d %H:%M} |")
            for field, title in (("by_kind", "question kind"), ("by_topic", "topic")):
                keys = sorted({k for r in done.values() for k in (r.metrics or {}).get(field, {})})
                if not keys:
                    continue
                lines += ["", f"Recall@5 / MRR by {title}:", "", "| Config | " + " | ".join(keys) + " |",
                          "|---" * (len(keys) + 1) + "|"]
                for label, r in done.items():
                    bk = (r.metrics or {}).get(field, {})
                    lines.append(f"| {label} | " + " | ".join(
                        f"{fmt(bk[k]['recall_at_5'])} / {fmt(bk[k]['mrr'])} (n={bk[k]['n']})" if k in bk else "—"
                        for k in keys) + " |")
            lines += ["", *[f"- {n}" for n in RETRIEVAL_NOTES]]
        else:
            lines.append("No completed retrieval runs yet.")
        lines += ["", "### Grounded answers", ""]
        if answers is not None:
            m = answers.metrics or {}
            lines += [f"LLM `{answers.config.get('llm_model')}`, {m.get('questions')} questions, "
                      f"run {answers.finished_at:%Y-%m-%d %H:%M} UTC.", "", "| Metric | Value |", "|---|---|"]
            lines += [f"| {k} | {fmt(v)} |" for k, v in m.items() if not isinstance(v, dict)]
            lines += ["", f"- {retrieval_note(answers.config)}", *[f"- {n}" for n in ANSWER_NOTES]]
        else:
            lines.append("No completed answers run yet (`make eval-answers`).")
        for label, title in (("tool_selection_planner", "Tool selection (investigation planner)"),
                             ("injection_resistance", "Prompt-injection resistance")):
            r = extra[label]
            if r is None:
                continue
            m = r.metrics or {}
            lines += ["", f"### {title}", "", f"LLM `{r.config.get('llm_model')}`, run {r.finished_at:%Y-%m-%d %H:%M} UTC.",
                      "", "| Metric | Value |", "|---|---|"]
            lines += [f"| {k} | {fmt(v)} |" for k, v in m.items() if not isinstance(v, (dict, list))]
            if r.config.get("method"):
                lines += ["", f"Method: {r.config['method']}"]
    path = ROOT / "RESULTS.md"
    path.write_text("\n".join(lines) + "\n")
    return path


def fmt(v: object) -> str:
    return f"{v:.3f}" if isinstance(v, float) and v <= 1 else str(v)


async def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="test", choices=["test", "tune", "all"])
    ap.add_argument("--dataset", default=None, help="dataset version (default: settings.evaluation_default_version)")
    ap.add_argument("--configs", default="all", help="comma list of A_lexical,B_vector,C_hybrid_rrf,D_hybrid_rrf_rerank")
    ap.add_argument("--answers", action="store_true", help="run grounded-answer checks instead of retrieval")
    ap.add_argument("--no-judge", action="store_true", help="answers: skip the LLM faithfulness judge (faster)")
    ap.add_argument("--extra", action="store_true", help="run tool-selection and prompt-injection evaluations")
    ap.add_argument("--limit", type=int, default=None, help="answers: only the first N questions")
    ap.add_argument("--results-only", action="store_true", help="only regenerate evaluation/RESULTS.md from stored runs")
    args = ap.parse_args()
    if args.results_only:
        async with get_sessionmaker()() as db:
            path = await write_results(db)
        await dispose_engine()
        print(f"wrote {path}")
        return 0
    s = get_settings()
    stamp = datetime.now(UTC).strftime("%Y%m%d-%H%M%S")
    env = {"python": platform.python_version(), "machine": platform.machine(), "system": platform.system(),
           "embedding_model": s.embedding_model, "llm_model": s.llm_model, "generated_at": datetime.now(UTC).isoformat()}
    runs = []
    async with get_sessionmaker()() as db:
        if args.extra:
            from app.evaluations.extra import run_injection, run_tool_selection

            ds = load_dataset(args.dataset)
            runs.append(await run_tool_selection(db, llm=get_llm(), dataset=ds))
            runs.append(await run_injection(db, llm=get_llm(), embedder=get_embedding_provider(), dataset=ds))
        elif args.answers:
            runs.append(await run_answers(db, embedder=get_embedding_provider(), llm=get_llm(), split=args.split,
                                          limit=args.limit, dataset=load_dataset(args.dataset),
                                          judge=not args.no_judge))
        else:
            labels = list(RETRIEVAL_CONFIGS) if args.configs == "all" else args.configs.split(",")
            for label in labels:
                print(f"running {label} ...", flush=True)
                runs.append(await run_retrieval(db, RETRIEVAL_CONFIGS[label], embedder=get_embedding_provider(),
                                                split=args.split, dataset=load_dataset(args.dataset)))
        results_path = await write_results(db) if args.split == "test" else None
    await dispose_engine()
    if results_path:
        print(f"updated {results_path}")

    for r in runs:
        if r.status != "completed":
            print(f"{r.config_label}: {r.status} {r.error}")
    first = runs[0]
    kind = "extra" if args.extra else ("answers" if args.answers else "retrieval")
    lines = [f"# OpsPilot {kind} evaluation — {first.dataset_name} {first.dataset_version} ({args.split} split)", "",
             f"- Generated: {env['generated_at']}", f"- Dataset hash: `{first.dataset_hash[:16]}`",
             f"- Environment: {env['system']} {env['machine']}, Python {env['python']}",
             f"- Embedding model: `{env['embedding_model']}`" + (f", LLM: `{env['llm_model']}`" if args.answers else ""),
             f"- Questions: {first.metrics.get('questions') if first.metrics else '?'}", ""]
    if args.extra:
        for r in runs:
            lines += [f"## {r.config_label}", "", f"Method: {r.config.get('method', '')}", "", "| Metric | Value |", "|---|---|"]
            lines += [f"| {k} | {fmt(v)} |" for k, v in (r.metrics or {}).items()] + [""]
    elif args.answers:
        m = first.metrics or {}
        lines += ["| Metric | Value |", "|---|---|"] + [f"| {k} | {fmt(v)} |" for k, v in m.items()]
    else:
        lines += ["| Config | " + " | ".join(c for _, c in COLS) + " |", "|---" * (len(COLS) + 1) + "|"]
        for r in runs:
            m = r.metrics or {}
            lines.append(f"| {r.config_label} | " + " | ".join(fmt(m.get(k, "—")) for k, _ in COLS) + " |")
        for field, title in (("by_kind", "question kind"), ("by_topic", "topic")):
            keys = sorted({k for r in runs for k in (r.metrics or {}).get(field, {})})
            if not keys:
                continue
            lines += ["", f"Recall@5 / MRR by {title}:", "", "| Config | " + " | ".join(keys) + " |",
                      "|---" * (len(keys) + 1) + "|"]
            for r in runs:
                bk = (r.metrics or {}).get(field, {})
                lines.append(f"| {r.config_label} | " + " | ".join(
                    f"{fmt(bk[k]['recall_at_5'])} / {fmt(bk[k]['mrr'])} (n={bk[k]['n']})" if k in bk else "—"
                    for k in keys) + " |")
    if args.extra:
        pass
    elif args.answers:
        lines += ["", "Notes:", *[f"- {retrieval_note(r.config)}" for r in runs[:1]], *[f"- {n}" for n in ANSWER_NOTES]]
    else:
        lines += ["", "Notes:", *[f"- {n}" for n in RETRIEVAL_NOTES]]
    md = "\n".join(lines) + "\n"
    out = ROOT / "reports" / f"{stamp}-{kind}-{args.split}"
    out.with_suffix(".md").write_text(md)
    out.with_suffix(".json").write_text(json.dumps({"environment": env, "runs": [
        {"id": str(r.id), "config_label": r.config_label, "config": r.config, "status": r.status, "metrics": r.metrics,
         "dataset_hash": r.dataset_hash, "split": r.split} for r in runs]}, indent=2))
    print(md)
    print(f"wrote {out.with_suffix('.md')}")
    return 0 if all(r.status == "completed" for r in runs) else 1


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
